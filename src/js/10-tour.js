/* ============ HatRack — getting-started tour (slides from guide/tour.js) ============
   guide/tour.js is generated by guide-src/build_guide.py from fresh screenshots, so the
   tour always matches the current release. It sets window.HATRACK_TOUR = { version, tracks, slides }. */

const tourData = () => (window.HATRACK_TOUR && window.HATRACK_TOUR.slides ? window.HATRACK_TOUR : null);
function cmpVer(a, b) {
  const pa = String(a || '0').split('.').map(n => parseInt(n, 10) || 0), pb = String(b || '0').split('.').map(n => parseInt(n, 10) || 0);
  for (let i = 0; i < 3; i++) { const d = (pa[i] || 0) - (pb[i] || 0); if (d) return d < 0 ? -1 : 1; }
  return 0;
}
const TRACKS = [['user', 'Everyday use'], ['admin', 'Setting up'], ['whatsnew', 'What’s new']];

/** slides for "What's new": a summary, then the slide each new item points to */
function whatsNewSlides(since) {
  const T0 = tourData(); if (!T0) return [];
  const rels = RELEASE.changelog.filter(r => (since ? cmpVer(r.version, since) > 0 : r.version === RELEASE.version));
  const items = rels.flatMap(r => r.items.map(it => ({ ...it, version: r.version })));
  if (!items.length) return [];
  const versions = [...new Set(items.map(i => i.version))];
  const out = [{
    id: 'wn-summary', title: `What’s new in HatRack ${RELEASE.version}`,
    text: versions.length > 1 ? `Everything that changed since ${since}.` : `Released ${fmtLongDate(rels[0].date)}.`,
    list: items.map(i => ({ title: i.title, text: i.text, version: versions.length > 1 ? i.version : '' })),
  }];
  const used = new Set();
  items.forEach(it => {
    const s = it.slide && T0.slides[it.slide];
    if (s && !used.has(s.id)) { used.add(s.id); out.push({ ...s, id: 'wn-' + s.id, title: esc(it.title), text: esc(it.text), tips: [], badge: `New in ${it.version}` }); }
  });
  return out;
}
function fmtLongDate(s) { const d = parseYMD(s); return d ? d.toLocaleDateString(undefined, { month: 'long', day: 'numeric', year: 'numeric' }) : s; }
function trackSlides(track, since) {
  const T0 = tourData(); if (!T0) return [];
  if (track === 'whatsnew') return whatsNewSlides(since);
  return (T0.tracks[track] || []).map(id => T0.slides[id]).filter(Boolean);
}

/* ---------- actions a slide can offer ("Try it") ---------- */
function tourAction(id) {
  const needsData = ['board', 'nest', 'select', 'list', 'outline', 'reports', 'export', 'triage'].includes(id);
  if (needsData && !D.tasks.length) loadSample();
  const go = v => { if (U.view !== v) setView(v); };
  switch (id) {
    case 'sample': if (D.tasks.length) toast('The sample rack is already here — or add it from Configure → Data.'); else loadSample(); return;
    case 'quick': go('board'); setTimeout(() => $('#quick')?.focus(), 60); return;
    case 'import': return openImport();
    case 'triage': go('board'); return openTriage();
    case 'board': case 'nest': case 'select': U.cursor = null; U.group = 'area'; U.lanes = 'none'; saveUI(); go('board'); renderAll(); return;
    case 'grid': U.cursor = null; U.group = 'priority'; U.lanes = 'area'; saveUI(); go('board'); renderAll(); return;
    case 'list': case 'outline': case 'reports': return go(id);
    case 'export': return openExport();
    case 'help': return helpMenu($('#btn-help'));
  }
  if (id.startsWith('cfg:')) { U.settingsTab = id.slice(4); saveUI(); setView('settings'); return; }
  if (id.startsWith('guide:')) return openGuide(id.slice(6));
}

/* ---------- the tour dialog ---------- */
let tourState = null;
function openTour(track = 'start', opts = {}) {
  if (!tourData()) {
    openModal({
      title: 'Getting started tour', body: `<p style="margin:0">The tour’s files aren’t next to the app. Keep the <code>guide</code> folder (with <code>tour.js</code> and the screenshots) in the same place as <code>index.html</code> — it’s in the download.</p>`,
      foot: `<button class="btn" data-close>Close</button><button class="btn primary" data-close id="tour-tips">Open shortcuts & tips</button>`,
    }).querySelector('#tour-tips').addEventListener('click', openHelp);
    return;
  }
  $('.tour-modal')?.closest('.modal-back')?.close();
  tourState = { track, i: 0, since: opts.since || null };
  if (track !== 'start' && track !== 'whatsnew') tourState.i = Math.min((U.tourPos || {})[track] || 0, trackSlides(track).length - 1);
  if (opts.step) tourState.i = Math.max(0, trackSlides(track).findIndex(s => s.id === opts.step));
  const m = openModal({ title: 'Getting started', cls: 'tour-modal', autofocus: false, help: 'tour', body: '<div class="tour" id="tour"></div>', onClose: () => { document.removeEventListener('keydown', onTourKey, true); U.tourSeen = true; saveUI(); tourState = null; } });
  m.querySelector('#tour').addEventListener('click', onTourClick);
  m.querySelector('#tour').addEventListener('mouseover', onTourHover);
  m.querySelector('#tour').addEventListener('mouseout', onTourHover);
  document.addEventListener('keydown', onTourKey, true);
  renderTour();
}
function renderTour() {
  const box = $('#tour'); if (!box || !tourState) return;
  const st = tourState; const T0 = tourData();
  const tabs = `<div class="tour-tabs" role="tablist">${TRACKS.map(([k, l]) => {
    const n = trackSlides(k, k === 'whatsnew' ? st.since : null).length;
    return n ? `<button role="tab" data-track="${k}" aria-selected="${st.track === k}">${l}<span class="n">${k === 'whatsnew' ? RELEASE.version : n}</span></button>` : '';
  }).join('')}</div>`;
  if (st.track === 'start') {
    const nu = trackSlides('user').length, na = trackSlides('admin').length;
    box.innerHTML = `${tabs}<div class="tour-welcome">
      <h2>Welcome to HatRack</h2>
      <p>A short tour with real screens. Pick the one that fits — you can switch tracks at the top whenever you like.</p>
      <div class="tour-choices">
        <button class="tour-choice" data-track="user"><b>Everyday use</b><span>Capture, import, triage, sort, nest subtasks, review and export.</span><small>${nu} steps · about ${Math.max(2, Math.round(nu * 0.25))} minutes</small></button>
        <button class="tour-choice admin" data-track="admin"><b>Setting up</b><span>For whoever owns the structure: groups, keywords, types, fields, backups, templates, hosting.</span><small>${na} steps · about ${Math.max(2, Math.round(na * 0.25))} minutes</small></button>
      </div>
      <h4 style="margin:6px 0 0;font:700 15px var(--font-display)">Jump to a topic</h4>
      <div class="tour-thumbs">${trackSlides('user').slice(1).filter(s => s.img).map(s => `<button data-jump="${s.id}"><img src="${esc(s.img)}" alt="" loading="lazy"><span>${s.title}</span></button>`).join('')}</div>
      <p class="muted sm">Screens and steps are refreshed with every release — this is HatRack ${esc(RELEASE.version)}${T0.built ? `, screens captured ${esc(fmtLongDate(T0.built))}` : ''}. Reopen the tour from Help (?) → Getting started tour.</p>
    </div>
    <div class="tour-foot"><span class="muted sm">${D.tasks.length ? '' : 'Tip: load the sample rack to follow along.'}</span><span class="spacer"></span>${D.tasks.length ? '' : '<button class="btn" data-ta="sample">Load the sample rack</button>'}<button class="btn" data-close>Skip for now</button></div>`;
    return;
  }
  const slides = trackSlides(st.track, st.track === 'whatsnew' ? st.since : null);
  if (!slides.length) { st.track = 'start'; return renderTour(); }
  st.i = Math.min(Math.max(0, st.i), slides.length - 1);
  if (st.track !== 'whatsnew') { U.tourPos = { ...(U.tourPos || {}), [st.track]: st.i }; saveUI(); }
  const s = slides[st.i]; const last = st.i === slides.length - 1;
  const pins = (s.pins || []).map((p, k) => `<span class="hlbox" data-n="${k + 1}" style="left:${p.box[0]}%;top:${p.box[1]}%;width:${p.box[2]}%;height:${p.box[3]}%"></span><span class="pin" data-n="${k + 1}" style="left:${p.x}%;top:${p.y}%">${k + 1}</span>`).join('');
  const legend = (s.pins || []).length ? `<ol class="tour-legend">${s.pins.map((p, k) => `<li data-n="${k + 1}"><span class="num">${k + 1}</span><span>${p.label}</span></li>`).join('')}</ol>` : '';
  const list = s.list ? `<ul class="tour-list">${s.list.map(it => `<li><b>${esc(it.title)}</b>${it.version ? ` <span class="badge">${esc(it.version)}</span>` : ''}<span>${esc(it.text)}</span></li>`).join('')}</ul>` : '';
  const img = s.img ? `<div class="tour-shot${s.icon ? ' icon' : ''}"><div class="tour-frame"><img src="${esc(s.img)}" alt="${esc(s.title)}" width="${s.w || ''}" height="${s.h || ''}" onerror="this.closest('.tour-shot').classList.add('missing')">${pins}</div></div>` : '';
  const nextTrack = st.track === 'user' && last ? 'admin' : null;
  box.innerHTML = `${tabs}
    <div class="tour-stage${s.img ? '' : ' noimg'}">
      ${img}
      <div class="tour-copy">
        ${s.badge ? `<span class="tour-badge">${esc(s.badge)}</span>` : ''}
        <div class="tour-count">Step ${st.i + 1} of ${slides.length}</div>
        <h3>${s.title}</h3>
        ${s.text ? `<p>${s.text}</p>` : ''}
        ${s.note && s.note !== s.text ? `<p class="tour-note">${esc(s.note)}</p>` : ''}
        ${legend}${list}
        ${s.tips && s.tips.length ? `<ul class="tour-tips">${s.tips.map(t => `<li>${t}</li>`).join('')}</ul>` : ''}
        <div class="tour-acts">${s.action ? `<button class="btn" data-ta="${esc(s.action.id)}">${esc(s.action.label)}</button>` : ''}${s.guide ? `<button class="linkish" data-guide="${esc(s.guide)}">More in the guide</button>` : ''}</div>
      </div>
    </div>
    <div class="tour-foot">
      <div class="tour-dots" role="tablist" aria-label="Steps">${slides.map((x, k) => `<button data-go="${k}" aria-label="Step ${k + 1}: ${esc(x.title.replace(/<[^>]+>/g, ''))}" aria-current="${k === st.i}"></button>`).join('')}</div>
      <span class="spacer"></span>
      <button class="btn" data-step="-1" ${st.i === 0 ? 'disabled' : ''}>Back</button>
      ${nextTrack ? `<button class="btn" data-close>Done</button><button class="btn primary" data-track="admin">Continue with Setting up</button>`
      : `<button class="btn primary" ${last ? 'data-close' : 'data-step="1"'}>${last ? 'Finish' : 'Next'}</button>`}
    </div>`;
  box.querySelector('.tour-foot .primary')?.focus({ preventScroll: true });
}
function onTourClick(e) {
  const b = e.target.closest('button'); if (!b || !tourState) return;
  if (b.dataset.track) { tourState.track = b.dataset.track; tourState.i = b.dataset.track === 'whatsnew' ? 0 : ((U.tourPos || {})[b.dataset.track] || 0); if (b.classList.contains('primary')) tourState.i = 0; return renderTour(); }
  if (b.dataset.step) { tourState.i += +b.dataset.step; return renderTour(); }
  if (b.dataset.jump) { tourState.track = 'user'; tourState.i = trackSlides('user').findIndex(s => s.id === b.dataset.jump); return renderTour(); }
  if (b.dataset.go) { tourState.i = +b.dataset.go; return renderTour(); }
  if (b.dataset.ta) {
    const id = b.dataset.ta;
    if (id === 'sample') { tourAction('sample'); return renderTour(); }
    $('.tour-modal')?.closest('.modal-back')?.close();
    tourAction(id);
    if (!['import', 'triage', 'export', 'help'].includes(id) && !id.startsWith('guide:')) toast('Tour paused — Help (?) → Getting started tour picks up where you left off.');
  }
}
function onTourHover(e) {
  const el = e.target.closest?.('[data-n]'); if (!el) return;
  const on = e.type === 'mouseover';
  $$(`#tour [data-n="${el.dataset.n}"]`).forEach(x => x.classList.toggle('on', on));
}
function onTourKey(e) {
  if (!tourState || $('#modal-root').lastElementChild?.querySelector('.tour-modal') == null) return;
  if (isTypingTarget(e.target) || e.metaKey || e.ctrlKey || e.altKey) return;
  if (tourState.track === 'start') return;
  if (e.key === 'ArrowRight' || e.key === 'PageDown') { const n = trackSlides(tourState.track, tourState.since).length; if (tourState.i < n - 1) { tourState.i++; renderTour(); } e.preventDefault(); e.stopPropagation(); }
  else if (e.key === 'ArrowLeft' || e.key === 'PageUp') { if (tourState.i > 0) { tourState.i--; renderTour(); } e.preventDefault(); e.stopPropagation(); }
}

/** first launch: welcome tour. After an update: what's new. Add ?notour to the address to skip both. */
function maybeAutoTour() {
  const skip = new URLSearchParams(location.search).has('notour');
  const seen = U.lastVersion, fresh = !D.tasks.length && !D.areas.length;
  if (cmpVer(seen, RELEASE.version) !== 0) { U.lastVersion = RELEASE.version; saveUI(); }
  if (skip || !tourData()) return;
  if (!seen) {
    if (fresh && !U.tourSeen) setTimeout(() => openTour('start'), 300);
    else if (whatsNewSlides('1.0.0').length) setTimeout(() => openTour('whatsnew', { since: '1.0.0' }), 300);
  } else if (cmpVer(seen, RELEASE.version) < 0 && whatsNewSlides(seen).length) setTimeout(() => openTour('whatsnew', { since: seen }), 300);
}
